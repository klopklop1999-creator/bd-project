-- =====================================================================
-- schema.sql: БД кредитного портфеля (на основе датасета Lending Club)
-- СУБД: PostgreSQL 14+
-- Запуск: psql -d <база> -f sql/schema.sql
--
-- Примечания:
--  * Все объекты создаются в схеме lending (для GRANT USAGE в roles.sql).
--  * Индексы под тяжёлые аналитические запросы НЕ создаются здесь:
--    они вынесены в sql/indexes.sql, чтобы на этапе 7 снять
--    EXPLAIN ANALYZE "до" и "после".
--  * Таблицы borrower_pii, collaterals, guarantors заполняются
--    синтетическими данными (в датасете этих сведений нет).
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS lending;
SET search_path = lending, public;

-- ---------------------------------------------------------------------
-- 1. Справочники
-- ---------------------------------------------------------------------

CREATE TABLE us_states (
    state_code  char(2)     PRIMARY KEY CHECK (state_code ~ '^[A-Z]{2}$'),
    state_name  varchar(60) NOT NULL UNIQUE
);

CREATE TABLE loan_grades (
    sub_grade   char(2)     PRIMARY KEY CHECK (sub_grade ~ '^[A-G][1-5]$'),
    grade       char(1)     NOT NULL CHECK (grade IN ('A','B','C','D','E','F','G')),
    CHECK (substr(sub_grade, 1, 1) = grade)
);

CREATE TABLE loan_purposes (
    purpose_id    smallint    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purpose_code  varchar(30) NOT NULL UNIQUE
);

CREATE TABLE loan_statuses (
    status_id    smallint    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status_name  varchar(70) NOT NULL UNIQUE
);

-- ---------------------------------------------------------------------
-- 2. Заёмщики
-- ---------------------------------------------------------------------

-- member_id в датасете пустой, поэтому заёмщик определяется эвристически:
-- identity_key = md5(штат | zip3 | дата первой кредитной линии | работодатель).
CREATE TABLE borrowers (
    borrower_id       bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identity_key      char(32)    NOT NULL UNIQUE,
    state_code        char(2)     NOT NULL REFERENCES us_states (state_code),
    zip3              char(3)     NOT NULL CHECK (zip3 ~ '^[0-9]{3}$'),
    earliest_cr_line  date,
    emp_title         text,
    created_at        timestamptz NOT NULL DEFAULT now()
);

-- Синтетические прямые идентификаторы. Вынесены в отдельную таблицу
-- (минимизация данных, отдельные права доступа).
CREATE TABLE borrower_pii (
    borrower_id  bigint       PRIMARY KEY REFERENCES borrowers (borrower_id) ON DELETE CASCADE,
    full_name    varchar(150) NOT NULL,
    birth_date   date         NOT NULL CHECK (birth_date >= DATE '1900-01-01'),
    phone        varchar(20)  NOT NULL UNIQUE,
    email        varchar(120) NOT NULL UNIQUE CHECK (email LIKE '%_@_%')
);

-- ---------------------------------------------------------------------
-- 3. Кредитные договоры
-- ---------------------------------------------------------------------

CREATE TABLE loans (
    loan_id              bigint        PRIMARY KEY,            -- id из датасета
    borrower_id          bigint        NOT NULL REFERENCES borrowers (borrower_id),
    sub_grade            char(2)       NOT NULL REFERENCES loan_grades (sub_grade),
    purpose_id           smallint      NOT NULL REFERENCES loan_purposes (purpose_id),
    status_id            smallint      NOT NULL REFERENCES loan_statuses (status_id),
    loan_amnt            numeric(10,2) NOT NULL CHECK (loan_amnt > 0),
    funded_amnt          numeric(10,2) NOT NULL CHECK (funded_amnt >= 0),
    funded_amnt_inv      numeric(10,2) CHECK (funded_amnt_inv >= 0),
    term_months          smallint      NOT NULL CHECK (term_months IN (36, 60)),
    int_rate             numeric(5,2)  NOT NULL CHECK (int_rate > 0 AND int_rate < 100),
    installment          numeric(8,2)  NOT NULL CHECK (installment > 0),
    issue_date           date          NOT NULL,               -- первое число месяца выдачи
    annual_inc           numeric(14,2) NOT NULL CHECK (annual_inc >= 0),
    emp_length_years     smallint      CHECK (emp_length_years BETWEEN 0 AND 10),
    home_ownership       varchar(10)   NOT NULL
                         CHECK (home_ownership IN ('MORTGAGE','RENT','OWN','ANY','OTHER','NONE')),
    verification_status  varchar(20)   NOT NULL
                         CHECK (verification_status IN ('Verified','Source Verified','Not Verified')),
    application_type     varchar(12)   NOT NULL
                         CHECK (application_type IN ('Individual','Joint App')),
    dti                  numeric(7,2)  CHECK (dti >= 0),
    initial_list_status  char(1)       CHECK (initial_list_status IN ('w','f')),
    disbursement_method  varchar(10)   CHECK (disbursement_method IN ('Cash','DirectPay')),
    CHECK (funded_amnt <= loan_amnt)
);

-- Кредитный профиль на момент заявки (1:1 с договором)
CREATE TABLE credit_profiles (
    loan_id                     bigint        PRIMARY KEY REFERENCES loans (loan_id) ON DELETE CASCADE,
    fico_range_low              smallint      NOT NULL CHECK (fico_range_low BETWEEN 300 AND 850),
    fico_range_high             smallint      NOT NULL CHECK (fico_range_high BETWEEN 300 AND 850),
    delinq_2yrs                 smallint      CHECK (delinq_2yrs >= 0),
    inq_last_6mths              smallint      CHECK (inq_last_6mths >= 0),
    mths_since_last_delinq      smallint      CHECK (mths_since_last_delinq >= 0),
    mths_since_last_record      smallint      CHECK (mths_since_last_record >= 0),
    open_acc                    smallint      CHECK (open_acc >= 0),
    pub_rec                     smallint      CHECK (pub_rec >= 0),
    revol_bal                   numeric(12,2),
    revol_util                  numeric(6,2)  CHECK (revol_util >= 0),
    total_acc                   smallint      CHECK (total_acc >= 0),
    collections_12_mths_ex_med  smallint      CHECK (collections_12_mths_ex_med >= 0),
    acc_now_delinq              smallint      CHECK (acc_now_delinq >= 0),
    tot_coll_amt                numeric(12,2) CHECK (tot_coll_amt >= 0),
    tot_cur_bal                 numeric(12,2) CHECK (tot_cur_bal >= 0),
    pub_rec_bankruptcies        smallint      CHECK (pub_rec_bankruptcies >= 0),
    tax_liens                   smallint      CHECK (tax_liens >= 0),
    bureau_extra                jsonb,       -- остальные ~51 колонка бюро кредитных историй
    CHECK (fico_range_high >= fico_range_low)
);

-- Состояние платежей по договору (1:1, часто обновляется)
CREATE TABLE loan_payments (
    loan_id                  bigint        PRIMARY KEY REFERENCES loans (loan_id) ON DELETE CASCADE,
    out_prncp                numeric(12,2) NOT NULL CHECK (out_prncp >= 0),
    out_prncp_inv            numeric(12,2) CHECK (out_prncp_inv >= 0),
    total_pymnt              numeric(14,2) NOT NULL CHECK (total_pymnt >= 0),
    total_pymnt_inv          numeric(14,2) CHECK (total_pymnt_inv >= 0),
    total_rec_prncp          numeric(12,2) NOT NULL CHECK (total_rec_prncp >= 0),
    total_rec_int            numeric(12,2) NOT NULL CHECK (total_rec_int >= 0),
    total_rec_late_fee       numeric(10,2) NOT NULL CHECK (total_rec_late_fee >= 0),
    recoveries               numeric(12,2) NOT NULL CHECK (recoveries >= 0),
    collection_recovery_fee  numeric(12,2) NOT NULL CHECK (collection_recovery_fee >= 0),
    last_pymnt_date          date,
    last_pymnt_amnt          numeric(12,2) CHECK (last_pymnt_amnt >= 0),
    next_pymnt_date          date,
    last_credit_pull_date    date,
    last_fico_range_low      smallint      CHECK (last_fico_range_low >= 0),
    last_fico_range_high     smallint      CHECK (last_fico_range_high >= 0)
);

-- ---------------------------------------------------------------------
-- 4. Реструктуризация и урегулирование
-- ---------------------------------------------------------------------

CREATE TABLE hardship_plans (
    hardship_id                                 bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id                                     bigint        NOT NULL UNIQUE REFERENCES loans (loan_id) ON DELETE CASCADE,
    hardship_type                               varchar(60),
    hardship_reason                             varchar(40),
    hardship_status                             varchar(20),
    deferral_term                               smallint      CHECK (deferral_term >= 0),
    hardship_amount                             numeric(10,2) CHECK (hardship_amount >= 0),
    hardship_start_date                         date,
    hardship_end_date                           date,
    payment_plan_start_date                     date,
    hardship_length                             smallint      CHECK (hardship_length >= 0),
    hardship_dpd                                smallint      CHECK (hardship_dpd >= 0),
    hardship_loan_status                        varchar(30),
    orig_projected_additional_accrued_interest  numeric(10,2) CHECK (orig_projected_additional_accrued_interest >= 0),
    hardship_payoff_balance_amount              numeric(12,2) CHECK (hardship_payoff_balance_amount >= 0),
    hardship_last_payment_amount                numeric(12,2) CHECK (hardship_last_payment_amount >= 0),
    CHECK (hardship_end_date IS NULL OR hardship_start_date IS NULL OR hardship_end_date >= hardship_start_date)
);

CREATE TABLE debt_settlements (
    settlement_id               bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id                     bigint        NOT NULL UNIQUE REFERENCES loans (loan_id) ON DELETE CASCADE,
    debt_settlement_flag_date   date,
    settlement_status           varchar(15),
    settlement_date             date,
    settlement_amount           numeric(12,2) CHECK (settlement_amount >= 0),
    settlement_percentage       numeric(6,2)  CHECK (settlement_percentage >= 0),
    settlement_term             smallint      CHECK (settlement_term >= 0)
);

-- ---------------------------------------------------------------------
-- 5. Созаёмщики (только для application_type = 'Joint App')
-- ---------------------------------------------------------------------

CREATE TABLE joint_applicants (
    loan_id                              bigint        PRIMARY KEY REFERENCES loans (loan_id) ON DELETE CASCADE,
    annual_inc_joint                     numeric(14,2) CHECK (annual_inc_joint >= 0),
    dti_joint                            numeric(7,2)  CHECK (dti_joint >= 0),
    verification_status_joint            varchar(20)
                                         CHECK (verification_status_joint IN ('Verified','Source Verified','Not Verified')),
    revol_bal_joint                      numeric(12,2),
    sec_app_fico_range_low               smallint      CHECK (sec_app_fico_range_low BETWEEN 300 AND 850),
    sec_app_fico_range_high              smallint      CHECK (sec_app_fico_range_high BETWEEN 300 AND 850),
    sec_app_earliest_cr_line             date,
    sec_app_inq_last_6mths               smallint      CHECK (sec_app_inq_last_6mths >= 0),
    sec_app_mort_acc                     smallint      CHECK (sec_app_mort_acc >= 0),
    sec_app_open_acc                     smallint      CHECK (sec_app_open_acc >= 0),
    sec_app_revol_util                   numeric(6,2)  CHECK (sec_app_revol_util >= 0),
    sec_app_open_act_il                  smallint      CHECK (sec_app_open_act_il >= 0),
    sec_app_num_rev_accts                smallint      CHECK (sec_app_num_rev_accts >= 0),
    sec_app_chargeoff_within_12_mths     smallint      CHECK (sec_app_chargeoff_within_12_mths >= 0),
    sec_app_collections_12_mths_ex_med   smallint      CHECK (sec_app_collections_12_mths_ex_med >= 0),
    sec_app_mths_since_last_major_derog  smallint      CHECK (sec_app_mths_since_last_major_derog >= 0)
);

-- ---------------------------------------------------------------------
-- 6. Обеспечение и поручители (синтетические данные)
-- ---------------------------------------------------------------------

CREATE TABLE collaterals (
    collateral_id    bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id          bigint        NOT NULL REFERENCES loans (loan_id) ON DELETE CASCADE,
    collateral_type  varchar(20)   NOT NULL
                     CHECK (collateral_type IN ('REAL_ESTATE','VEHICLE','DEPOSIT','EQUIPMENT','SECURITIES')),
    market_value     numeric(12,2) NOT NULL CHECK (market_value > 0),
    appraisal_date   date          NOT NULL,
    description      text
);

CREATE TABLE guarantors (
    guarantor_id      bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id           bigint        NOT NULL REFERENCES loans (loan_id) ON DELETE CASCADE,
    full_name         varchar(150)  NOT NULL,
    birth_date        date          NOT NULL CHECK (birth_date >= DATE '1900-01-01'),
    phone             varchar(20)   NOT NULL,
    passport_data     varchar(11)   NOT NULL,
    guarantee_amount  numeric(10,2) NOT NULL CHECK (guarantee_amount > 0),
    UNIQUE (loan_id, passport_data)
);

-- ---------------------------------------------------------------------
-- 7. Журнал аудита (заполняется триггерами из triggers_functions.sql)
-- ---------------------------------------------------------------------

CREATE TABLE audit_log (
    log_id      bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name  text        NOT NULL,
    operation   char(1)     NOT NULL CHECK (operation IN ('I','U','D')),
    record_pk   text,
    changed_by  name        NOT NULL DEFAULT current_user,
    changed_at  timestamptz NOT NULL DEFAULT now(),
    old_data    jsonb,
    new_data    jsonb
);

-- ---------------------------------------------------------------------
-- 8. Индексы (базовые; тяжёлые индексы под этап 7 в sql/indexes.sql)
-- ---------------------------------------------------------------------

-- Фильтрация и группировка заёмщиков по штату (B-tree)
CREATE INDEX idx_borrowers_state_code ON borrowers (state_code);

-- Поиск поручителей и обеспечения по договору (B-tree)
CREATE INDEX idx_guarantors_loan_id   ON guarantors (loan_id);
CREATE INDEX idx_collaterals_loan_id  ON collaterals (loan_id);

-- Поиск по JSON-показателям бюро кредитных историй (GIN)
CREATE INDEX idx_credit_profiles_bureau_gin ON credit_profiles USING gin (bureau_extra jsonb_path_ops);

-- Просмотр журнала аудита по таблице и времени (B-tree)
CREATE INDEX idx_audit_log_table_time ON audit_log (table_name, changed_at);

-- ---------------------------------------------------------------------
-- 9. Комментарии: классификация данных (используется в матрице доступа)
-- ---------------------------------------------------------------------

COMMENT ON TABLE us_states        IS 'Справочник штатов. Категория: открытые';
COMMENT ON TABLE loan_grades      IS 'Справочник рейтингов займа. Категория: коммерческая тайна (методика скоринга)';
COMMENT ON TABLE loan_purposes    IS 'Справочник целей займа. Категория: открытые';
COMMENT ON TABLE loan_statuses    IS 'Справочник статусов займа. Категория: открытые';
COMMENT ON TABLE borrowers        IS 'Заёмщики (косвенные идентификаторы: zip3, работодатель, дата первой кредитной линии). Категория: ПДн (косвенные)';
COMMENT ON TABLE borrower_pii     IS 'Прямые идентификаторы заёмщика (синтетика). Категория: ПДн';
COMMENT ON TABLE loans            IS 'Кредитные договоры. Категория: коммерческая тайна; annual_inc: ПДн (финансовые сведения)';
COMMENT ON TABLE credit_profiles  IS 'Кредитный профиль заёмщика на момент заявки. Категория: ПДн / коммерческая тайна';
COMMENT ON TABLE loan_payments    IS 'Состояние платежей по договору. Категория: коммерческая тайна';
COMMENT ON TABLE hardship_plans   IS 'Планы реструктуризации. Категория: коммерческая тайна';
COMMENT ON TABLE debt_settlements IS 'Урегулирование задолженности. Категория: коммерческая тайна';
COMMENT ON TABLE joint_applicants IS 'Данные созаёмщика. Категория: ПДн';
COMMENT ON TABLE collaterals      IS 'Залог (синтетика). Категория: коммерческая тайна';
COMMENT ON TABLE guarantors       IS 'Поручители (синтетика). Категория: ПДн';
COMMENT ON TABLE audit_log        IS 'Журнал аудита. Категория: коммерческая тайна, доступ только администратору';
